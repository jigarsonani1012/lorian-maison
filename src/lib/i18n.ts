export type Language = "English" | "Français" | "Italiano" | "日本語" | "العربية";
export type Currency = "USD" | "EUR" | "GBP" | "AED" | "JPY";

export const CURRENCY_RATES: Record<Currency, { rate: number; locale: string; symbol: string }> = {
  USD: { rate: 1, locale: "en-US", symbol: "$" },
  EUR: { rate: 0.92, locale: "fr-FR", symbol: "€" },
  GBP: { rate: 0.79, locale: "en-GB", symbol: "£" },
  AED: { rate: 3.67, locale: "ar-AE", symbol: "AED " },
  JPY: { rate: 155, locale: "ja-JP", symbol: "¥" },
};

export const formatPriceWithCurrency = (price: number | null, currency: string = "USD") => {
  if (price === null) return "Price Upon Request";
  const curr = (CURRENCY_RATES[currency as Currency] ? currency : "USD") as Currency;
  const config = CURRENCY_RATES[curr];
  const converted = price * config.rate;

  return new Intl.NumberFormat(config.locale, {
    style: "currency",
    currency: curr,
    maximumFractionDigits: curr === "JPY" ? 0 : 0,
  }).format(converted);
};

